log = []


def sub_re(pattern, new, label, flags=0):
    global t
    n = len(re.findall(pattern, t, flags))
    if n != 1:
        sys.exit('%s：预期 1 次，实际 %d 次' % (label, n))
    t = re.sub(pattern, new, t, count=1, flags=flags)
    log.append(label)


