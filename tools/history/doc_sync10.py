"""项目文档同步：描边取消、改为血量比例配色，并记录两处连带取舍。"""
import re
import sys
from pathlib import Path

DOC = Path(r'D:\2048') / '项目文档.md'
t = DOC.read_text(encoding='utf-8')
log = []


def sub_re(pattern, new, label, flags=0):
    global t
    n = len(re.findall(pattern, t, flags))
    if n != 1:
        sys.exit('%s：预期 1 次，实际 %d 次' % (label, n))
    t = re.sub(pattern, new, t, count=1, flags=flags)
    log.append(label)


sub_re(r'^\| 数字描边 \| 方块数字加\*\*浅色描边\*\*：低血方块的上半露出暗底，深色数字必须有浅色衬托才看得清 \|$',
       '| 血量配色 | 掉血的我方方块按血量比例改色：**绿(>2/3) / 黄(>1/3) / 红(其余)**；'
       '满血方块保持阵营色。颜色与阈值是具名常量（`HP_HURT` / `HP_CRIT` / `HP_COL_*`） |',
       '§12.6 表格：数字描边 -> 血量配色', re.M)

sub_re(r'^\| 数字在低血方块上会压到暗底（数字本身是深色，底色是浅色） \| 改成\*\*浅色描边\*\*；'
       r'曾试过加档位刻度，你判断不需要，\*\*已取消\*\* \|$',
       '| 数字在低血方块上会压到暗底（数字是深色、底色是浅色） | 最终改为**按血量比例给我方方块上色**'
       '（绿/黄/红）；档位刻度与数字描边都按你的判断**取消了** |',
       '§13.4 表格：描边 -> 血量配色', re.M)

SEC = """

### 13.7 待确认：血量配色连带的两处取舍

按你的字面要求（"我方方块"）实现后，有两处身份色被血量色覆盖，需要你定：

| 对象 | 现状 | 取舍 |
| --- | --- | --- |
| **友方支援碉堡** | 掉血时也变绿/黄/红 | 图例里"蓝色＝友方碉堡"在掉血状态下不再成立。要把建筑排除是一行条件的事 |
| **我方核心** | 掉血时也变绿/黄/红 | 受损核心显示红色，警报感更强；代价是盖掉了金色的核心色。核心身份仍靠轮廓与 ✣ 标记可辨 |

另外提醒一句：数字是深色、而低血方块的上半是暗底，所以**低血方块上的数字可读性**
在没有描边的情况下仍需你眼睛确认——这正是上一版加描边想解决的问题。
"""

if '13.7 待确认' not in t:
    t = t.rstrip('\n') + SEC
    log.append('追加 §13.7 待确认')

DOC.write_text(t, encoding='utf-8', newline='')
print('项目文档已同步：')
for a in log:
    print('  - %s' % a)
