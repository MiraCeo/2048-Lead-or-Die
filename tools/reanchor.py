"""重新锚定补丁：当引擎里被补丁覆盖的那一行被改动后，把补丁的 old 换到新文本。

补丁名自带线索：`<块首 40 字符>@main[起:止]`。所以只要拿名字里 `@main[` 之前的部分
去当前引擎里找唯一匹配的行，就能把 old 重新对上去。

只改 old（引擎侧）；new（教程侧）保持不动——按你的要求，教程这一轮不碰。
"""
import importlib.util
import re
import sys
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
except Exception:
    pass

ROOT = Path(r'D:\2048')
SRC = ROOT / 'src'
MAIN = SRC / 'main.script.js'
PATCHES = SRC / 'tutorial.patches.py'


def load():
    spec = importlib.util.spec_from_file_location('tp', PATCHES)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.PATCHES


def emit(patches):
    chunks = []
    for p in patches:
        if 'new_file' in p:
            chunks.append('    {\n        "name": %r,\n        "old": %r,\n'
                          '        "new_file": %r,\n    },\n'
                          % (p['name'], p['old'], p['new_file']))
        else:
            chunks.append('    {\n        "name": %r,\n        "old": %r,\n'
                          '        "new": %r,\n    },\n' % (p['name'], p['old'], p['new']))
    PATCHES.write_text(
        '"""GENERATED by tools/derive_patches.py -- do not edit by hand.\n\n'
        'Ordered literal block replacements applied to src/main.script.js to produce\n'
        "the tutorial's embedded script. Each anchor must match exactly once; the build\n"
        'fails loudly otherwise, so engine edits cannot silently drift the tutorial.\n\n'
        'Block boundaries are whole lines INCLUDING the trailing newline.\n'
        'A patch carrying "new_file" takes its replacement from that file under src/,\n'
        'so lesson scaffolding is edited as .js rather than as a Python literal.\n\n'
        'Regenerate with:  python tools/derive_patches.py\n'
        '"""\n\n'
        'PATCHES = [\n' + ''.join(chunks) + ']\n',
        encoding='utf-8', newline='')


def main():
    js = MAIN.read_text(encoding='utf-8')
    lines = js.split('\n')
    patches = load()
    changed = 0

    for p in patches:
        if js.count(p['old']) == 1:
            continue
        # 搜索键不能用补丁名里的线索（它来自函数名），也不能只靠固定长度的前缀：
        # 被改动的行可能已经和旧文本只剩很短的公共前缀（本轮那条补丁就是如此）。
        # 改为：在所有行里找与 old 首行「公共前缀最长」的那一行，要求唯一且足够长。
        first_line = p['old'].split('\n')[0]
        best_len, best = 0, []
        for i, l in enumerate(lines):
            n = 0
            while n < len(first_line) and n < len(l) and first_line[n] == l[n]:
                n += 1
            if n > best_len:
                best_len, best = n, [i]
            elif n == best_len and n > 0:
                best.append(i)
        if best_len < 12 or len(best) != 1:
            print('无法自动重锚（最长公共前缀 %d 字符，命中 %d 行）：%s'
                  % (best_len, len(best), p['name']))
            continue
        hits = best
        # 一条补丁可能跨多行（例如 performSwap + worldStep），
        # 而线索只来自首行，所以要按原 old 的行数取同样多行。
        nlines = p['old'].count('\n') or 1
        chunk = lines[hits[0]:hits[0] + nlines]
        if len(chunk) != nlines:
            print('重锚失败（行数不足）：%s' % p['name'])
            continue
        new_old = '\n'.join(chunk)
        if p['old'].endswith('\n'):
            new_old += '\n'
        if js.count(new_old) != 1:
            print('重锚后仍不唯一：%s' % p['name'])
            continue
        print('重锚：%s  (%d 行)' % (p['name'], nlines))
        print('  旧 old 首段：%r' % p['old'][:70])
        print('  新 old 首段：%r' % new_old[:70])
        p['old'] = new_old
        changed += 1

    if changed:
        emit(patches)
        print('\n已重写补丁文件（%d 条重锚）' % changed)
    else:
        print('无需重锚')


if __name__ == '__main__':
    main()
